def render_pptx(outline: dict, template_id: str, font_name: str = "Calibri") -> bytes:
    tpl = TEMPLATES.get(template_id, TEMPLATES["modern"])

    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)

    _render_cover(prs, outline.get("title", "Untitled"), tpl, font_name)

    for idx, slide_data in enumerate(outline.get("slides", [])):
        _render_content_slide(
            prs,
            slide_data.get("heading", ""),
            slide_data.get("bullets", []),
            tpl,
            font_name,
            slide_index=idx,
        )

    buf = io.BytesIO()
    prs.save(buf)
    buf.seek(0)
    return buf.read()

def _set_bg(slide, color):
    """Set solid background color on a slide."""
    bg = slide.background
    fill = bg.fill
    fill.solid()
    fill.fore_color.rgb = color


def _render_cover(prs, title, tpl, font_name):
    """Cover slide: uses blank layout, one big centered text box."""
    slide = prs.slides.add_slide(prs.slide_layouts[6])  # blank
    _set_bg(slide, tpl["cover_bg"])

    # Big accent block on left
    _add_accent_block(slide, tpl["accent"])

    # Title text box
    title_box = slide.shapes.add_textbox(
        Inches(1.2), Inches(2.8), Inches(10.9), Inches(2)
    )
    tf = title_box.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = MSO_ANCHOR.MIDDLE
    p = tf.paragraphs[0]
    p.alignment = PP_ALIGN.LEFT
    run = p.add_run()
    run.text = title
    run.font.name = font_name
    run.font.size = Pt(tpl["cover_title_size"])
    run.font.bold = True
    run.font.color.rgb = tpl["title_color"]

    # Subtitle strip
    sub_box = slide.shapes.add_textbox(
        Inches(1.2), Inches(4.9), Inches(10.9), Inches(0.5)
    )
    stf = sub_box.text_frame
    sp = stf.paragraphs[0]
    sub_run = sp.add_run()
    sub_run.text = "Generated by Studyforge AI"
    sub_run.font.name = font_name
    sub_run.font.size = Pt(14)
    sub_run.font.color.rgb = tpl["accent"]


def _add_accent_block(slide, color):
    """Small accent rectangle in the top-left for visual anchor."""
    from pptx.enum.shapes import MSO_SHAPE
    shape = slide.shapes.add_shape(
        MSO_SHAPE.RECTANGLE,
        Inches(1.2), Inches(2.2),
        Inches(0.8), Inches(0.1),
    )
    shape.fill.solid()
    shape.fill.fore_color.rgb = color
    shape.line.fill.background()


def _render_content_slide(prs, heading, bullets, tpl, font_name, slide_index=0):
    """Content slide with alternating layouts for visual variety."""
    from pptx.enum.shapes import MSO_SHAPE

    slide = prs.slides.add_slide(prs.slide_layouts[6])
    _set_bg(slide, tpl["bg"])

    # Alternate layouts every 3 slides
    layout_type = slide_index % 3

    if layout_type == 0:
        _layout_standard(slide, heading, bullets, tpl, font_name)
    elif layout_type == 1:
        _layout_sidebar(slide, heading, bullets, tpl, font_name)
    else:
        _layout_centered(slide, heading, bullets, tpl, font_name)


def _layout_standard(slide, heading, bullets, tpl, font_name):
    """Standard: heading top, accent line, bullets below."""
    from pptx.enum.shapes import MSO_SHAPE

    # Small accent square in corner
    corner = slide.shapes.add_shape(
        MSO_SHAPE.OVAL, Inches(12.5), Inches(0.4), Inches(0.35), Inches(0.35)
    )
    corner.fill.solid()
    corner.fill.fore_color.rgb = tpl["accent"]
    corner.line.fill.background()

    # Heading
    hb = slide.shapes.add_textbox(Inches(0.7), Inches(0.5), Inches(11.6), Inches(1.1))
    tf = hb.text_frame
    tf.word_wrap = True
    run = tf.paragraphs[0].add_run()
    run.text = heading
    run.font.name = font_name
    run.font.size = Pt(tpl["title_size"])
    run.font.bold = True
    run.font.color.rgb = tpl["title_color"]

    # Accent underline
    line = slide.shapes.add_shape(
        MSO_SHAPE.RECTANGLE, Inches(0.7), Inches(1.65), Inches(1.4), Inches(0.06)
    )
    line.fill.solid()
    line.fill.fore_color.rgb = tpl["accent"]
    line.line.fill.background()

    # Bullets with numbered circles
    _draw_bullets(slide, bullets, tpl, font_name, x=Inches(0.7), y=Inches(2.0), w=Inches(11.9))


def _layout_sidebar(slide, heading, bullets, tpl, font_name):
    """Sidebar layout: colored strip on left with slide number, content on right."""
    from pptx.enum.shapes import MSO_SHAPE

    # Left sidebar
    sidebar = slide.shapes.add_shape(
        MSO_SHAPE.RECTANGLE, Inches(0), Inches(0), Inches(2.5), Inches(7.5)
    )
    sidebar.fill.solid()
    sidebar.fill.fore_color.rgb = tpl["accent"]
    sidebar.line.fill.background()

    # Big number on sidebar
    num_box = slide.shapes.add_textbox(Inches(0.3), Inches(2.8), Inches(2), Inches(2))
    num_tf = num_box.text_frame
    num_p = num_tf.paragraphs[0]
    num_p.alignment = PP_ALIGN.CENTER
    num_run = num_p.add_run()
    num_run.text = "◆"
    num_run.font.name = font_name
    num_run.font.size = Pt(80)
    num_run.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)

    # Heading on right
    hb = slide.shapes.add_textbox(Inches(3), Inches(0.7), Inches(9.7), Inches(1.3))
    htf = hb.text_frame
    htf.word_wrap = True
    hrun = htf.paragraphs[0].add_run()
    hrun.text = heading
    hrun.font.name = font_name
    hrun.font.size = Pt(tpl["title_size"])
    hrun.font.bold = True
    hrun.font.color.rgb = tpl["title_color"]

    # Bullets on right
    _draw_bullets(slide, bullets, tpl, font_name, x=Inches(3), y=Inches(2.1), w=Inches(9.7))


def _layout_centered(slide, heading, bullets, tpl, font_name):
    """Centered emphasis: big heading in middle, bullets stacked below."""
    from pptx.enum.shapes import MSO_SHAPE

    # Top accent bar (short, centered)
    bar = slide.shapes.add_shape(
        MSO_SHAPE.RECTANGLE, Inches(5.9), Inches(0.6), Inches(1.5), Inches(0.08)
    )
    bar.fill.solid()
    bar.fill.fore_color.rgb = tpl["accent"]
    bar.line.fill.background()

    # Centered heading
    hb = slide.shapes.add_textbox(Inches(1), Inches(1.0), Inches(11.3), Inches(1.4))
    htf = hb.text_frame
    htf.word_wrap = True
    hp = htf.paragraphs[0]
    hp.alignment = PP_ALIGN.CENTER
    hrun = hp.add_run()
    hrun.text = heading
    hrun.font.name = font_name
    hrun.font.size = Pt(tpl["title_size"] + 4)
    hrun.font.bold = True
    hrun.font.color.rgb = tpl["title_color"]

    # Bullets — centered layout
    _draw_bullets(slide, bullets, tpl, font_name, x=Inches(1.5), y=Inches(2.8), w=Inches(10.3))


def _draw_bullets(slide, bullets, tpl, font_name, x, y, w):
    """Draw bullet list with colored markers."""
    body_box = slide.shapes.add_textbox(x, y, w, Inches(4.5))
    body_tf = body_box.text_frame
    body_tf.word_wrap = True

    for i, bullet in enumerate(bullets):
        if i == 0:
            p = body_tf.paragraphs[0]
        else:
            p = body_tf.add_paragraph()
        p.space_after = Pt(14)

        marker = p.add_run()
        marker.text = "●  "
        marker.font.name = font_name
        marker.font.size = Pt(tpl["body_size"])
        marker.font.color.rgb = tpl["accent"]
        marker.font.bold = True

        text_run = p.add_run()
        text_run.text = str(bullet)
        text_run.font.name = font_name
        text_run.font.size = Pt(tpl["body_size"])
        text_run.font.color.rgb = tpl["body_color"]
